"""Turn the pixel grids from sprite.py into compact SVG path data for the mod."""
import json, sys
import sprite

EMOTES = {
    'heart': [".RR.RR.",
              "RRRRRRR",
              "RRRRRRR",
              ".RRRRR.",
              "..RRR..",
              "...R..."],
    'z': ["ZZZZ",
          "..Z.",
          ".Z..",
          "ZZZZ"],
}
EXTRA_PAL = {'Z': '#7fa7c9', 'R': '#ff5a6e'}


def runs(grid):
    """{char: 'M..h..v1h-..z...'} merging horizontal runs of one colour."""
    out = {}
    for y, row in enumerate(grid):
        row = ''.join(row)
        x = 0
        while x < len(row):
            c = row[x]
            if c == '.':
                x += 1
                continue
            n = 1
            while x + n < len(row) and row[x + n] == c:
                n += 1
            out.setdefault(c, []).append(f"M{x} {y}h{n}v1h-{n}z")
            x += n
    return {c: ''.join(v) for c, v in out.items()}


pal = dict(sprite.PAL)
pal.update(EXTRA_PAL)

frames = {}
for name, g in sprite.FRAMES.items():
    frames[name] = [[pal[c], d] for c, d in runs(g).items()]
emotes = {}
for name, g in EMOTES.items():
    emotes[name] = [[pal[c], d] for c, d in runs([list(r) for r in g]).items()]

ts = (
    "// Generated by gen_art.py from the 32x32 Ripachok sprite: one SVG path per colour per frame.\n"
    "export type Layer = [fill: string, d: string]\n\n"
    f"export const FRAMES: Record<string, Layer[]> = {json.dumps(frames, separators=(',', ':'))}\n\n"
    f"export const EMOTES: Record<string, Layer[]> = {json.dumps(emotes, separators=(',', ':'))}\n\n"
    "// The same art as character grids, for the terminal's half-block renderer ('.' = transparent).\n"
    f"export const RGB: Record<string, number> = {json.dumps({c: int(v[1:], 16) for c, v in pal.items()}, separators=(',', ':'))}\n\n"
    f"export const GRIDS: Record<string, string[]> = {json.dumps({k: [''.join(r) for r in v] for k, v in sprite.FRAMES.items()}, separators=(',', ':'))}\n\n"
    f"export const EMOTE_GRIDS: Record<string, string[]> = {json.dumps(EMOTES, separators=(',', ':'))}\n"
)
open(sys.argv[1], 'w').write(ts)
print(len(ts), 'chars')
